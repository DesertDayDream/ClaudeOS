const out = {};
for (const [key, [title, icon, aliases = []]] of Object.entries(APPS)) {
  const s = icon.startsWith('si') ? si[icon] : null;
  if (icon.startsWith('si') && !s) throw new Error(`simple-icons has no ${icon}`);
  out[key] = { title, hex: s ? s.hex : icon, path: s ? s.path : null, aliases };
}

const file = path.join(ROOT, 'public', 'apps.js');
fs.writeFileSync(file, `// Generated by scripts/make-apps.mjs (npm run apps). Logos: simple-icons, CC0.
// Apps an employee can be connected to: an MCP server ("claude.ai Gmail", "blender") or a name in its SKILL.md.
export const APPS = ${JSON.stringify(out)};

// "claude.ai Google Drive", "claude_ai_Google_Drive", "plugin:x:blender" -> "googledrive" / "blender"
export function normServer(name) {
  return String(name).replace(/^claude[._ ]ai[ _]/i, '').replace(/^plugin[:_][^:_]+[:_]/i, '').toLowerCase().replace(/[^a-z0-9]/g, '');
}

// the app an MCP server is for, or null
export function appForServer(name) {
  const n = normServer(name).replace(/(mcp|server)$/, '');
  if (!n) return null;
  for (const [key, a] of Object.entries(APPS)) {
    if (n === key || a.aliases.includes(n) || n === a.title.toLowerCase().replace(/[^a-z0-9]/g, '')) return key;
  }
  for (const [key] of Object.entries(APPS)) if (key.length > 3 && n.startsWith(key)) return key;
  return null;
}

const COMMON_WORDS = new Set(['x', 'box', 'zoom', 'linear', 'notion', 'teams', 'sentry', 'obsidian', 'miro']);

// apps named in a SKILL.md: as integration tools (mcp__claude_ai_Gmail__search) or by name ("Gmail")
export function appsInText(text) {
  const found = new Map();
  for (const m of String(text).matchAll(/mcp__([A-Za-z0-9_.-]+?)__/g)) {
    const key = appForServer(m[1]);
    found.set(key || 'mcp:' + m[1], 'tools');
  }
  for (const [key, a] of Object.entries(APPS)) {
    // a brand counts only as written (capitalized); everyday words like "zoom" count only as tools
    if (found.has(key) || COMMON_WORDS.has(key)) continue;
    const name = a.title.replace(/[.*+?^\${}()|[\\]\\\\]/g, '\\\\$&');
    if (new RegExp(\`\\\\b\${name}\\\\b\`).test(text)) found.set(key, 'named');
  }
  return [...found].map(([key, why]) => ({ key, why }));
}
`);
